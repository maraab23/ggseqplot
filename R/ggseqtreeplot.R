#' Sequence Regression Tree Plot
#'
#' Function for rendering regression trees of sequences (obtained with
#' \code{\link[TraMineR:seqtree]{TraMineR::seqtree}}) with \code{\link[ggplot2]{ggplot2}}
#' \insertCite{wickham2016}{ggseqplot}. The function re-produces the
#' tree plots rendered with \code{\link[TraMineR:seqtreedisplay]{TraMineR::seqtreedisplay}}
#' \insertCite{gabadinho2011,studer2011}{ggseqplot} without requiring an
#' installation of 'GraphViz'. Each node of the tree is displayed as a sequence
#' plot produced by one of the \code{ggseq*plot} functions of this package.
#'
#' @param tree A regression tree of sequences (class \code{seqtree}) created with
#' \code{\link[TraMineR:seqtree]{TraMineR::seqtree}}. Trees of class \code{disstree}
#' (\code{\link[TraMineR:disstree]{TraMineR::disstree}}) can be used if \code{seqdata} is specified.
#' @param seqdata State sequence object (class \code{stslist}) created with the
#' \code{\link[TraMineR:seqdef]{TraMineR::seqdef}} function. If \code{NULL} (default)
#' the sequence object stored in the \code{tree} object is used.
#' @param type Type of the sequence plot shown in the nodes of the tree:
#' \code{"d"} for state distribution plots (default, \code{\link{ggseqdplot}}),
#' \code{"i"} for index plots (\code{\link{ggseqiplot}}),
#' \code{"f"} for sequence frequency plots (\code{\link{ggseqfplot}}),
#' \code{"ms"} for modal state plots (\code{\link{ggseqmsplot}}), or
#' \code{"mt"} for mean time plots (\code{\link{ggseqmtplot}}).
#' @param only.leaf If \code{TRUE} sequence plots are only shown for the terminal
#' nodes (leaves) of the tree; the inner nodes are shown as text boxes. Default is \code{FALSE}.
#' @param with.legend Specifies if a legend of the states is shown (default is \code{TRUE})
#' @param with.quality Specifies if the global quality measures of the tree
#' (Pseudo F, Pseudo R2, and Levene statistic, rounded to two decimals) are
#' shown below the tree (default is \code{TRUE}).
#' The measures are rendered as plot tag and can be moved (see Details).
#' @param quality.multiline If \code{TRUE} the global quality measures are
#' printed in separate lines instead of one line, which is useful if they are
#' placed next to the root node (default is \code{FALSE}).
#' @param title.size Font size of the node titles (split condition, n, s2, and
#' next split variable); default is \code{9}. Smaller values might be required
#' for large trees.
#' @param label.width Maximum number of characters per line for the split labels.
#' Longer labels (e.g., splits over sets of factor levels) are wrapped. Default is \code{30}.
#' @param common.y If \code{TRUE} all node plots share the same y-axis range,
#' which eases the comparison of the nodes. Only used for mean time plots
#' (\code{type = "mt"}); the y-axes of state distribution plots and modal state
#' plots always range from 0 to 1. Default is \code{FALSE}.
#' @param node.layers A ggplot component (e.g., a scale or a theme) or a list of
#' ggplot components that is added to each of the node plots, e.g.,
#' \code{list(scale_x_discrete(labels = ...), theme(plot.caption = element_text(size = 6)))}.
#' The components are added after the default layout of the node plots and
#' therefore overwrite it. Default is \code{NULL}.
#' @param ... additional arguments passed on to the plot function specified with
#' \code{type} (e.g. \code{border = TRUE} or \code{sortv = "from.start"} for index plots).
#' If \code{sortv} is a vector (of the same length as the sequence data), it is
#' subsetted for each node.
#'
#' @return A tree plot created by using \code{\link[ggplot2]{ggplot2}}. If stored as
#' object the resulting list object (of class gg and ggplot) also contains the
#' data describing the nodes of the tree (position, label, n, discrepancy,
#' split variable, and the indices of the cases in each node).
#'
#' @export
#'
#' @details The function walks through the tree object generated by
#' \code{\link[TraMineR:seqtree]{TraMineR::seqtree}} and stores the information
#' of each node in a data frame. Like in
#' \code{\link[TraMineR:seqtreedisplay]{TraMineR::seqtreedisplay}} each node shows
#' the split condition (or "Root"), the number of (weighted) cases (n), the
#' discrepancy of the sequences within the node (s2), and -- for inner nodes --
#' the variable used for the next split along with its R2.
#'
#' The positions of the nodes are computed with a simple algorithm:
#' the terminal nodes (leaves) are placed next to each other from left to right,
#' and every inner node is centered above its two child nodes. The vertical
#' position reflects the depth of a node.
#'
#' For each node a sequence plot is generated by calling the function
#' specified with \code{type} on the respective subset of the sequence data.
#' The resulting plots are placed on an empty plot ("canvas") using
#' \code{\link[ggplot2:annotation_custom]{ggplot2::annotation_custom}}. The
#' edges of the tree are drawn with \code{\link[ggplot2:geom_segment]{ggplot2::geom_segment}}.
#' Axis titles and legends of the node plots are removed. Instead, a common
#' legend for the whole tree is shown at the bottom of the plot.
#'
#' Note that the node plots are drawn as images on the canvas. Therefore, the
#' appearance of the node plots cannot be changed afterwards using \code{+}.
#' Instead, scales, themes, or other ggplot components that should be applied to
#' all node plots can be specified with the \code{node.layers} argument.
#' The overall plot (title, legend, ...), however, can be
#' adjusted just like any other ggplot (e.g., \code{+ labs(title = "My tree")}).
#' The global quality measures are rendered as plot tag. Their position can be
#' changed with \code{theme(plot.tag.position = ..., plot.tag.location = "panel")}
#' (see examples). The legend can be moved with \code{theme(legend.position = ...)}
#' and rearranged with \code{guides(fill = guide_legend(...))}.
#' For large trees, it is recommended to save the plot with a large size, e.g. by using
#' \code{\link[ggplot2:ggsave]{ggplot2::ggsave}} with appropriate \code{width} and
#' \code{height} values.
#'
#' @author Marcel Raab
#'
#' @references
#'   \insertAllCited{}
#'
#' @examples
#' library(TraMineR)
#' library(ggplot2)
#'
#' # Use example data from TraMineR: mvad data set
#' data(mvad)
#'
#' # We use only a sample of 300 cases
#' set.seed(1)
#' mvad <- mvad[sample(nrow(mvad), 300), ]
#' mvad.seq <- seqdef(mvad[, 17:86], xtstep = 6)
#'
#' # Compute dissimilarities and grow the regression tree
#' mvad.diss <- seqdist(mvad.seq, method = "HAM")
#' mvad.tree <- seqtree(mvad.seq ~ male + Grammar + funemp + gcse5eq,
#'                      data = mvad, diss = mvad.diss, R = 100, max.depth = 3)
#'
#' # Tree with state distribution plots
#' # (similar to TraMineR::seqtreedisplay, which requires GraphViz)
#' ggseqtreeplot(mvad.tree)
#'
#' \donttest{
#' # Tree with index plots (only shown for the terminal nodes)
#' ggseqtreeplot(mvad.tree, type = "i", only.leaf = TRUE)
#'
#' # Tree with mean time plots using a common y-axis for all nodes
#' ggseqtreeplot(mvad.tree, type = "mt", common.y = TRUE)
#'
#' # make use of ggplot functions for modifying the plot
#' ggseqtreeplot(mvad.tree) +
#'   labs(title = "Regression tree of school-to-work trajectories") +
#'   theme(legend.position = "top")
#'
#' # adjust all node plots: x-axis labels and size of split information
#' ggseqtreeplot(mvad.tree,
#'               node.layers = list(
#'                 scale_x_discrete(breaks = c(1, 13, 25, 37, 49, 61),
#'                                  labels = 1993:1998),
#'                 theme(plot.caption = element_text(size = 6))
#'               ))
#'
#' # layout similar to TraMineR::seqtreedisplay: legend in the upper left
#' # and global quality in the upper right corner
#' ggseqtreeplot(mvad.tree, quality.multiline = TRUE) +
#'   theme(plot.tag.location = "panel",
#'         plot.tag.position = c(1, 1),
#'         plot.tag = element_text(hjust = 1, vjust = 1),
#'         legend.position = "inside",
#'         legend.position.inside = c(0, 1),
#'         legend.justification = c(0, 1),
#'         legend.direction = "vertical")
#' }
#'
#' @import ggplot2
#' @importFrom rlang .data
ggseqtreeplot <- function(tree,
                          seqdata = NULL,
                          type = "d",
                          only.leaf = FALSE,
                          with.legend = TRUE,
                          with.quality = TRUE,
                          quality.multiline = FALSE,
                          title.size = 9,
                          label.width = 30,
                          common.y = FALSE,
                          node.layers = NULL,
                          ...) {
  if (!inherits(tree, "disstree")) {
    stop("tree is not a regression tree object, use 'TraMineR::seqtree' to create one")
  }

  seqdata <- seqdata %||% tree$info$object

  if (!inherits(seqdata, "stslist")) {
    stop("data are not stored as sequence object, use 'TraMineR::seqdef' to create one")
  }

  if (nrow(seqdata) != length(tree$root$info$ind)) {
    stop("number of sequences in seqdata must match the number of cases used to grow the tree")
  }

  if (!type %in% c("d", "i", "f", "ms", "mt")) {
    stop("`type` must be one of \"d\", \"i\", \"f\", \"ms\", or \"mt\"")
  }

  if (!is.logical(only.leaf) || !is.logical(with.legend) ||
      !is.logical(with.quality) || !is.logical(quality.multiline) ||
      !is.logical(common.y)) {
    stop("the arguments `only.leaf`, `with.legend`, `with.quality`, `quality.multiline`, and `common.y` have to be objects of type logical")
  }

  if (common.y == TRUE && type != "mt") {
    cli::cli_warn(c(
      "!" = "{.arg common.y} is only used for mean time plots ({.code type = \"mt\"}) and is ignored."
    ))
    common.y <- FALSE
  }

  if (!is.numeric(title.size) || !is.numeric(label.width)) {
    stop("the arguments `title.size` and `label.width` have to be numeric")
  }

  # a single component (e.g. theme(...)) is put into a list
  if (!is.null(node.layers) && !identical(class(node.layers), "list")) {
    node.layers <- list(node.layers)
  }


  # function used for plotting the nodes
  plotfun <- switch(type,
                    d = ggseqdplot,
                    i = ggseqiplot,
                    f = ggseqfplot,
                    ms = ggseqmsplot,
                    mt = ggseqmtplot)

  plotargs <- list(...)


  # walk through the tree and collect the information on each node -----------

  # leaves are numbered from left to right (= their x position);
  # inner nodes are centered above their kids

  nodelist <- list()
  leafcount <- 0

  walk_tree <- function(node, parent, label) {
    id <- length(nodelist) + 1
    nodelist[[id]] <<- NA # reserve slot so that kids get higher ids

    if (is.null(node$split)) {
      leafcount <<- leafcount + 1
      x <- leafcount
      splitvar <- NA_character_
      splitr2 <- NA_real_
    } else {
      splitlabs <- treesplitlabs(node$split, width = label.width)
      x_kids <- c(walk_tree(node$kids[[1]], parent = id, label = splitlabs[1]),
                  walk_tree(node$kids[[2]], parent = id, label = splitlabs[2]))
      x <- mean(x_kids)
      splitvar <- colnames(tree$data)[node$split$varindex]
      splitr2 <- node$split$info$R2
    }

    nodelist[[id]] <<- dplyr::tibble(
      id = id,
      parent = parent,
      depth = node$info$depth,
      x = x,
      y = -node$info$depth,
      label = label,
      n = node$info$n,
      s2 = node$info$vardis,
      splitvar = splitvar,
      splitr2 = splitr2,
      leaf = is.null(node$split),
      ind = list(node$info$ind)
    )

    return(x)
  }

  walk_tree(tree$root, parent = NA_integer_, label = "Root")

  nodedata <- dplyr::bind_rows(nodelist) |>
    dplyr::mutate(
      nodetitle = glue::glue("n: {treeformat(.data$n)}, s2: {treeformat(.data$s2)}"),
      nodesplit = dplyr::if_else(
        .data$leaf,
        "",
        glue::glue("Split: {.data$splitvar} (R\u00b2 = {sprintf('%.2f', .data$splitr2)})")
      )
    )


  # size of node boxes (in units of the canvas) -------------------------------

  boxwidth <- .9
  boxheight <- .75

  nleaves <- sum(nodedata$leaf)
  maxdepth <- max(nodedata$depth)


  # edges connecting the nodes ------------------------------------------------

  edgedata <- nodedata |>
    dplyr::filter(!is.na(.data$parent)) |>
    dplyr::select("id", "parent", xend = "x", yend = "y", "leaf") |>
    dplyr::left_join(nodedata |> dplyr::select("id", "x", "y"),
                     by = c("parent" = "id")) |>
    dplyr::mutate(
      # start at bottom of parent box (or center of text box if only.leaf)
      y = .data$y - dplyr::if_else(only.leaf, 0, boxheight / 2),
      # end at top of child box (or center of text box if only.leaf)
      yend = .data$yend + dplyr::if_else(only.leaf & !.data$leaf, 0, boxheight / 2)
    )


  # sequence plots for each node ----------------------------------------------

  nodetheme <- theme(
    legend.position = "none",
    plot.title = element_text(size = title.size, face = "bold",
                              hjust = .5, margin = margin(0, 0, 2, 0)),
    plot.subtitle = element_text(size = title.size * .9,
                                 hjust = .5, margin = margin(0, 0, 2, 0)),
    plot.caption = element_text(size = title.size * .9, face = "bold",
                                hjust = .5, margin = margin(2, 0, 0, 0)),
    plot.title.position = "plot",
    plot.caption.position = "plot",
    axis.text = element_text(size = title.size * .7),
    # extra space on the right side for the last x-axis label
    plot.margin = margin(4, 12, 4, 6),
    plot.background = element_rect(fill = "white", color = "grey50")
  )

  make_nodeplot <- function(i) {
    nodeargs <- plotargs
    ind <- nodedata$ind[[i]]

    # sortv vectors have to be subsetted for each node
    if (!is.null(nodeargs$sortv) && length(nodeargs$sortv) > 1) {
      nodeargs$sortv <- nodeargs$sortv[ind]
    }

    suppressMessages(
      nodeplot <- do.call(plotfun, c(list(seqdata = seqdata[ind, ]), nodeargs)) +
        labs(x = NULL, y = NULL,
             title = nodedata$label[i],
             subtitle = nodedata$nodetitle[i],
             caption = nodedata$nodesplit[i]) +
        nodetheme +
        node.layers
    )

    return(nodeplot)
  }

  shownodes <- which(!only.leaf | nodedata$leaf)

  nodeplots <- purrr::map(shownodes, make_nodeplot)

  # common y-axis: extend the y-axis of each node plot to the largest y value
  # found in any of the node plots (including error bars)
  if (common.y == TRUE) {
    ymax <- max(purrr::map_dbl(nodeplots, nodeplotymax))

    nodeplots <- purrr::map(nodeplots, ~ .x + expand_limits(y = ymax))
  }

  nodeannotations <- purrr::map2(
    shownodes, nodeplots,
    ~ annotation_custom(
      ggplotGrob(.y),
      xmin = nodedata$x[.x] - boxwidth / 2,
      xmax = nodedata$x[.x] + boxwidth / 2,
      ymin = nodedata$y[.x] - boxheight / 2,
      ymax = nodedata$y[.x] + boxheight / 2
    )
  )


  # inner nodes as text boxes (only if only.leaf = TRUE) ----------------------

  textnodedata <- nodedata |>
    dplyr::filter(only.leaf & !.data$leaf) |>
    dplyr::mutate(label = gsub("\n", "<br>", .data$label),
                  text = glue::glue("**{label}**<br>{nodetitle}<br>**{nodesplit}**"))


  # legend: invisible layer with the states and colors of the root plot -------

  legenddata <- get_guide_data(make_nodeplot(1) + theme(legend.position = "bottom"),
                               "fill")

  legenddata <- legenddata |>
    dplyr::mutate(
      state = factor(.data$.label, levels = .data$.label),
      x = nodedata$x[1],
      y = nodedata$y[1]
    )

  legendcolors <- legenddata$fill
  names(legendcolors) <- legenddata$.label


  # global quality of the tree ------------------------------------------------

  # shown as tag (instead of caption), because tags can be placed anywhere
  # using theme(plot.tag.position = ..., plot.tag.location = "panel")
  qualitytag <- NULL

  if (with.quality == TRUE) {
    qualitystats <- tree$info$adjustment$stat

    stars <- function(pval) {
      stars <- as.character(cut(pval, c(0, 0.001, 0.01, 0.05, 1),
                                labels = c("***", "**", "*", ""),
                                include.lowest = TRUE))
      stars[is.na(stars)] <- ""
      return(stars)
    }

    # one line (default) or one line per measure (quality.multiline = TRUE)
    if (quality.multiline == TRUE) {
      sep_title <- "\n"
      sep_stats <- "\n"
    } else {
      sep_title <- ": "
      sep_stats <- ", "
    }

    qualitytag <- glue::glue(
      "Global quality{sep_title}",
      "Pseudo F: {sprintf('%.2f', qualitystats['Pseudo F', 1])}",
      "{stars(qualitystats['Pseudo F', 2])}{sep_stats}",
      "Pseudo R\u00b2: {sprintf('%.2f', qualitystats['Pseudo R2', 1])}",
      "{stars(qualitystats['Pseudo R2', 2])}{sep_stats}",
      "Levene: {sprintf('%.2f', qualitystats['Levene', 1])}",
      "{stars(qualitystats['Levene', 2])}"
    )
  }


  # plot ----------------------------------------------------------------------

  ggtree <- ggplot(nodedata, aes(x = .data$x, y = .data$y)) +
    geom_tile(data = legenddata,
              aes(fill = .data$state),
              width = 0, height = 0) +
    geom_segment(data = edgedata,
                 aes(xend = .data$xend, yend = .data$yend),
                 color = "grey40", linewidth = .4,
                 arrow = arrow(length = unit(1.5, "mm"), type = "closed")) +
    nodeannotations +
    scale_fill_manual(values = legendcolors) +
    coord_cartesian(xlim = c(.5, nleaves + .5),
                    ylim = c(-maxdepth - boxheight / 2 - .05, -1 + boxheight / 2 + .05),
                    expand = FALSE,
                    clip = "off") +
    labs(tag = qualitytag) +
    theme_void() +
    theme(
      legend.position = "bottom",
      legend.title = element_blank(),
      legend.margin = margin(10, 0, 0, 0),
      plot.tag.position = "bottom",
      plot.tag = element_text(size = rel(.8), face = "plain",
                              margin = margin(10, 0, 0, 0)),
      plot.background = element_rect(fill = "white", color = NA),
      plot.margin = margin(15, 15, 10, 15)
    )

  if (nrow(textnodedata) > 0) {
    ggtree <- ggtree +
      ggtext::geom_richtext(data = textnodedata,
                            aes(label = .data$text),
                            size = title.size / .pt,
                            fill = "white", label.color = "grey50",
                            label.r = unit(0, "pt"),
                            label.padding = unit(c(4, 6, 4, 6), "pt"))
  }

  if (with.legend == FALSE) {
    ggtree <- ggtree +
      theme(legend.position = "none")
  }

  return(ggtree)
}


# labels of the two kids of a split (adapted from TraMineR::disstree2dot)
treesplitlabs <- function(split, width) {
  if (!is.null(split$breaks)) {
    splitlabs <- c(paste("<=", treeformat(split$breaks)),
                   paste(">", treeformat(split$breaks)))
  } else {
    splitlabs <- c(paste(split$labels[split$index == 1], collapse = ", "),
                   paste(split$labels[split$index == 2], collapse = ", "))
  }

  if (!is.null(split$naGroup)) {
    splitlabs[split$naGroup] <- paste(splitlabs[split$naGroup], "with NA")
  }

  # wrap long labels (e.g., splits over many factor levels)
  splitlabs <- purrr::map_chr(splitlabs,
                              ~ paste(strwrap(.x, width = width), collapse = "\n"))

  return(splitlabs)
}


# largest y value of a plot (across all layers, e.g. bars and error bars)
nodeplotymax <- function(plot) {
  ymax <- purrr::map_dbl(
    seq_along(plot$layers),
    ~ max(c(-Inf, layer_data(plot, .x)$ymax), na.rm = TRUE)
  )

  return(max(ymax))
}


# format numbers with at most two decimals, without trailing zeros
# (each value separately to avoid padding), e.g. 712, 22.92, 521.77
treeformat <- function(x) {
  purrr::map_chr(x, ~ format(round(.x, 2), scientific = FALSE))
}
